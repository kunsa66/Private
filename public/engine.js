function tenGod(me, other) {
  const em = stemEl(me), eo = stemEl(other), same = me % 2 === other % 2;
  if (em === eo) return same ? "비견" : "겁재";
  if ((em + 1) % 5 === eo) return same ? "식신" : "상관";
  if ((em + 2) % 5 === eo) return same ? "편재" : "정재";
  if ((eo + 2) % 5 === em) return same ? "편관" : "정관";
  return same ? "편인" : "정인";
}
